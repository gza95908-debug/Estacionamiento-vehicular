-- Ejecutar en Supabase > SQL Editor.
create table if not exists public.estacionamientos (
  id bigint generated by default as identity primary key,
  nombre text not null,
  latitud double precision not null,
  longitud double precision not null,
  cantidad_lugares integer not null check (cantidad_lugares > 0),
  predio text not null,
  cobertura text not null check (cobertura in ('Techado', 'Al aire libre')),
  constraint coordenadas_validas check (
    latitud between -90 and 90 and longitud between -180 and 180
  )
);

-- Para el prototipo escolar: habilita operaciones desde la clave pública.
-- No usar esta política abierta en una aplicación con datos privados o de producción.
alter table public.estacionamientos enable row level security;

drop policy if exists "lectura publica escolar" on public.estacionamientos;
drop policy if exists "insercion publica escolar" on public.estacionamientos;
drop policy if exists "actualizacion publica escolar" on public.estacionamientos;
drop policy if exists "eliminacion publica escolar" on public.estacionamientos;

create policy "lectura publica escolar" on public.estacionamientos
for select to anon using (true);
create policy "insercion publica escolar" on public.estacionamientos
for insert to anon with check (true);
create policy "actualizacion publica escolar" on public.estacionamientos
for update to anon using (true) with check (true);
create policy "eliminacion publica escolar" on public.estacionamientos
for delete to anon using (true);

grant select, insert, update, delete on public.estacionamientos to anon;
grant usage, select on sequence public.estacionamientos_id_seq to anon;
